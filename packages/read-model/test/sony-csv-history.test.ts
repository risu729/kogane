describe("canonical Sony balance tie differential", () => {
  let store: QualityStore;
  const corrected = new Map<string, string>();
  beforeAll(() => {
    store = new QualityStore();
    let random = 1295;
    const next = () => (random = (Math.imul(random, 1664525) + 1013904223) >>> 0);
    store.db.transaction(() => {
      for (let index = 0; index < 36; index++) {
        const source = index % 3 === 0 ? "paypay" : "sony-bank";
        const account = `synthetic-balance-${index}`;
        const csvPresent = index % 4 !== 0;
        const csvOlder = index % 5 === 0;
        const jsonLast = index % 2 === 0;
        const at = `2099-04-${String((index % 20) + 3).padStart(2, "0")}T00:00:00Z`;
        const amount = String((next() % 1000) + 1);
        const specs = [
          {
            parser: "sony-bank-history-json",
            dataset: "yen-history-page-0001",
            amount: "9999",
            asOf: "2099-04-02",
          },
          ...(csvPresent
            ? [
                {
                  parser: "sony-bank-history-csv",
                  dataset: "yen-history-csv",
                  amount,
                  asOf: csvOlder ? "2099-04-01" : "2099-04-02",
                },
              ]
            : []),
        ];
        const run = store.run({
          source,
          at,
          artifacts: specs.map(({ dataset }) => ({ dataset, key: dataset })),
        });
        const order = [...specs.entries()];
        if (jsonLast) order.reverse();
        for (const [offset, spec] of order)
          parsed(store, run.artifacts[offset]!, spec.parser, [
            {
              kind: "balance",
              sourceAccount: account,
              metric: "available_after_transaction",
              instrument: "JPY",
              amountMinor: Number(spec.amount),
              amountText: spec.amount,
              amountScale: 0,
              asOf: spec.asOf,
              rawLocator: "synthetic",
              extra: {},
            },
          ]);
        if (source === "sony-bank" && csvPresent && !csvOlder && jsonLast)
          corrected.set(account, amount);
      }
    })();
  });
  afterAll(() => store.db.close());
  test("frozen query differs only for same-day Sony CSV/JSON ties, including JSON-only and older CSV controls", () => {
    const query = latestBalancesSql({}, 0, PAGE_LIMIT);
    const now = store.db.query(query.sql).all(...(query.args as SQLQueryBindings[])) as Record<
      string,
      unknown
    >[];
    const old = store.db
      .query(LEGACY_BALANCES)
      .all(...(query.args as SQLQueryBindings[])) as Record<string, unknown>[];
    const comparable = (row: Record<string, unknown>) => ({
      source: row.source_id,
      account: row.source_account,
      metric: row.metric,
      instrument: row.instrument,
      asOf: row.as_of,
      amount: row.amount_minor,
      parser: row.parser,
    });
    const expected = old.map((row) => {
      const amount = corrected.get(String(row.source_account));
      return comparable(
        amount === undefined
          ? row
          : { ...row, amount_minor: amount, parser: "sony-bank-history-csv@1.0.0" },
      );
    });
    expect(now.map(comparable)).toEqual(expected);
    expect(corrected.size).toBeGreaterThan(0);
    expect(
      now.some(
        (row) => row.source_id === "sony-bank" && row.parser === "sony-bank-history-json@1.0.0",
      ),
    ).toBe(true);
  });
  test("query plans preserve access paths without table statistics", () => {
    expect(
      store.db.query("SELECT name FROM sqlite_master WHERE name='sqlite_stat1'").all(),
    ).toEqual([]);
    const query = latestBalancesSql({}, 0, PAGE_LIMIT);
    const currentPlan = explain(store.db, query.sql, query.args).map((step) => step.detail);
    const legacyPlan = explain(store.db, LEGACY_BALANCES, query.args).map((step) => step.detail);
    // The same existing sorter gets three Sony tie terms. No seek or scan changes.
    expect(currentPlan).toContain("USE TEMP B-TREE FOR LAST 11 TERMS OF ORDER BY");
    expect(legacyPlan).toContain("USE TEMP B-TREE FOR LAST 8 TERMS OF ORDER BY");
    const access = (details: string[]) =>
      details
        .map((detail) =>
          detail.replace(/LAST (?:8|11) TERMS OF ORDER BY/u, "LAST SONY_TIE_TERMS OF ORDER BY"),
        )
        .sort();
    expect(access(currentPlan)).toEqual(access(legacyPlan));
  });
});

