// Literal SQL generated by the shipped reader at a4be666, before the Sony exclusion.
// Keep this independent of the current CTE builders and projection predicates.
const LEGACY = readFileSync(join(import.meta.dir, "sony-transactions-legacy.sql"), "utf8");
const FIXTURE = join(
  import.meta.dir,
  "../../../tests/fixtures/observation-pipeline/sony-bank-parser-boundaries",
);
type Row = { id: number; parser: string; external_id: string; description: string };

function current(store: QualityStore, scope: CollectionScope = {}, legacy = false): Row[] {
  const result: Row[] = [];
  const filters = scopePredicates(scope, ["source", "account", "from", "to", "q"]);
  for (let offset = 0; ; offset += 500) {
    const page = transactionsSql(scope, offset);
    const sql = legacy
      ? LEGACY.replace("WHERE 1\n      ORDER BY", `WHERE ${filters.where}\n      ORDER BY`)
      : page.sql;
    const rows = store.db.query(sql).all(...(page.args as SQLQueryBindings[])) as Row[];
    result.push(...rows.slice(0, 500));
    if (rows.length <= 500) return result;
  }
}

function parsed(
  store: QualityStore,
  artifact: number,
  parser: string,
  rows: readonly TransactionObservation[],
): void {
  const parse = store.id();
  store.db.run(
    "INSERT INTO parse_runs(id,fetch_artifact_id,parser_name,parser_version,parsed_at,status,warnings_json) VALUES(?,?,?,'1.0.0','2099-01-01','pending','[]')",
    [parse, artifact, parser],
  );
  for (const row of rows)
    store.db.run(
      `INSERT INTO transaction_observations(parse_run_id,source_account,external_id,status,amount_minor,amount_text,amount_scale,currency,description,as_of,raw_locator,extra_json)
      VALUES(?,?,?,?,?,?,?,?,?,?,?,?)`,
      [
        parse,
        row.sourceAccount,
        row.externalId ?? null,
        row.status ?? null,
        row.amountMinor ?? null,
        row.amountText ?? null,
        row.amountScale ?? null,
        row.currency ?? null,
        row.description ?? null,
        row.asOf ?? null,
        row.rawLocator,
        JSON.stringify(row.extra),
      ],
    );
  store.db.run("UPDATE parse_runs SET status='ok' WHERE id=?", [parse]);
  store.db.run(
    "INSERT INTO publication_events(fetch_artifact_id,parser_name,previous_parse_run_id,new_parse_run_id,kind,actor,reason,occurred_at) VALUES(?,?,NULL,?,'normal','pipeline','parse_ok','2099-01-01')",
    [artifact, parser, parse],
  );
  store.db.run(
    "INSERT INTO published_parse_runs(fetch_artifact_id,parser_name,parse_run_id,parser_version,published_at,publication_kind) VALUES(?,?,?,'1.0.0','2099-01-01','normal')",
    [artifact, parser, parse],
  );
}

function seedSony(store: QualityStore, csvPresent: boolean): void {
  const first = JSON.parse(readFileSync(join(FIXTURE, "yen-history-page-0001.json"), "utf8"));
  const repeat = {
    ...first.transactionHistInfo[0],
    abridgmentObj: "synthetic-repeat",
    applicationExchRt: "1",
    currencyCdSpndl: "JPY",
    currencyCdStl: "USD",
    otherPrtyCcyCd: "USD",
  };
  const unique = {
    ...first.transactionHistInfo[0],
    abridgmentObj: "synthetic-other",
    transactionAmt: "2",
    transactionAftBal: "3",
  };
  first.countCnt = 4;
  first.returnCnt = 3;
  first.transactionHistInfo = [repeat, unique, { ...unique, transactionAmt: "3" }];
  const second = {
    countCnt: 4,
    returnCnt: 1,
    errors: [],
    responseBizCommon: first.responseBizCommon,
    transactionHistInfo: [repeat],
  };
  const csv =
    "取引日,摘要,参考情報,通貨,預入額,引出額,差引残高\n2026/09/01,synthetic-repeat,synthetic-reference,JPY,1000,,2500\n2026/09/01,synthetic-other,,JPY,2,,3\n2026/09/01,synthetic-other,,JPY,3,,3\n2026/09/01,synthetic-repeat,synthetic-reference,JPY,1000,,2500\n";
  const specs = [
    {
      dataset: "yen-history-page-0001",
      parser: sonyBankHistoryJson,
      body: JSON.stringify(first),
      mime: "application/json",
    },
    {
      dataset: "yen-history-page-0002",
      parser: sonyBankHistoryJson,
      body: JSON.stringify(second),
      mime: "application/json",
    },
    ...(csvPresent
      ? [{ dataset: "yen-history-csv", parser: sonyBankHistoryCsv, body: csv, mime: "text/csv" }]
      : []),
  ];
  const run = store.run({
    source: "sony-bank",
    at: "2026-09-30T00:00:00Z",
    artifacts: specs.map(({ dataset }) => ({ dataset, key: dataset })),
  });
  specs.forEach((spec, index) => {
    const meta: ArtifactMeta = {
      id: run.artifacts[index]!,
      sourceId: "sony-bank",
      runStatus: "success",
      runFailureCount: 0,
      runWindow: { from: "2026-09-01", to: "2026-09-30" },
      dataset: spec.dataset,
      mime: spec.mime,
      url: null,
      fetchedAt: "2026-09-30T00:00:00Z",
      sha256: "0".repeat(64),
    };
    const rows = spec.parser
      .parse(new TextEncoder().encode(spec.body), meta)
      .observations.filter((row): row is TransactionObservation => row.kind === "transaction");
    parsed(store, meta.id, spec.parser.name, rows);
  });
}

describe("Sony current history uses the CSV only", () => {
  test("identical rows on separate JSON pages appear twice, each from the CSV", () => {
    const store = new QualityStore();
    try {
      seedSony(store, true);
      const rows = current(store, { source: "sony-bank", q: "synthetic-repeat" });
      expect(rows).toHaveLength(2);
      expect(rows.every((row) => row.parser.startsWith("sony-bank-history-csv@"))).toBe(true);
      expect(new Set(rows.map((row) => row.external_id)).size).toBe(2);
      expect(current(store)).toEqual(current(store, {}, true));
      // JSON's unique exchange codes remain in the stored evidence observations.
      expect(
        store.db
          .query(
            "SELECT count(*) n FROM transaction_observations WHERE json_extract(extra_json,'$.currencyCdStl')='USD'",
          )
          .get(),
      ).toEqual({ n: 2 });
    } finally {
      store.db.close();
    }
  });
  test("historically published JSON without a CSV never becomes a current transaction fallback", () => {
    const store = new QualityStore();
    try {
      seedSony(store, false);
      expect(current(store, {}, true)).toHaveLength(3);
      expect(current(store)).toEqual([]);
    } finally {
      store.db.close();
    }
  });
});

describe("Sony CSV differential on a scaled random CORE store", () => {
  let store: QualityStore;
  beforeAll(() => {
    store = new QualityStore();
    let random = 1182;
    const next = () => (random = (Math.imul(random, 1664525) + 1013904223) >>> 0);
    store.db.transaction(() => {
      for (let i = 0; i < 20; i++) {
        const sony = i % 3 === 0;
        const run = store.run({
          source: sony ? "sony-bank" : "paypay",
          at: `2099-01-${String(1 + (i % 28)).padStart(2, "0")}T00:00:00Z`,
          outcome: i % 11 === 0 ? "failed" : "success",
          artifacts: [
            { dataset: sony ? "yen-history-page-0001" : "paypay-csv", key: `synthetic-${i}` },
          ],
        });
        const parser = sony
          ? i % 2 === 0
            ? "sony-bank-history-json"
            : "sony-bank-history-csv"
          : "paypay-csv";
        parsed(
          store,
          run.artifacts[0]!,
          parser,
          Array.from({ length: 40 + (next() % 10) }, (_, j): TransactionObservation => ({
            kind: "transaction",
            sourceAccount: sony ? "sony-bank:deposit:JPY" : "paypay:synthetic",
            externalId: `synthetic-${i}-${j}`,
            amountMinor: next() % 100,
            amountText: "1",
            amountScale: 0,
            currency: "JPY",
            asOf: `2099-01-${String(1 + (next() % 28)).padStart(2, "0")}`,
            description: next() % 2 === 0 ? "synthetic-a" : "synthetic-b",
            rawLocator: `csv:row:${j + 2}`,
            extra: {
              _kogane: {
                sourceView: sony
                  ? parser.endsWith("json")
                    ? "provider-json"
                    : "official-csv"
                  : "csv",
              },
            },
          })),
        );
      }
    })();
  });
  afterAll(() => store.db.close());
  test.each([
    {},
    { source: "paypay" },
    { source: "sony-bank" },
    { q: "synthetic-a" },
    { from: "2099-01-10", to: "2099-01-20" },
    { account: "sony-bank:deposit:JPY" },
  ])("frozen shipped SQL differs only by JSON rows for %j", (scope) => {
    expect(current(store, scope)).toEqual(
      current(store, scope, true).filter(
        (row) => !row.parser.startsWith("sony-bank-history-json@"),
      ),
    );
  });
  test("no table statistics or added query-plan scans", () => {
    expect(
      store.db.query("SELECT name FROM sqlite_master WHERE name='sqlite_stat1'").all(),
    ).toEqual([]);
    const page = transactionsSql({}, 0);
    // SQLite may reorder indexed seeks; their multiplicity and access paths stay equal.
    expect(
      explain(store.db, page.sql, page.args)
        .map((step) => step.detail)
        .sort(),
    ).toEqual(
      explain(store.db, LEGACY, page.args)
        .map((step) => step.detail)
        .sort(),
    );
  });
});

test("retained CSV publication recovers month-end and deduplicates legacy monthly windows and repeated runs", () => {
  const store = new QualityStore();
  const header = "取引日,摘要,参考情報,通貨,預入額,引出額,差引残高\n";
  const old = "2099/03/31,synthetic-month-end,,JPY,1,,1\n";
  const recent = "2099/04/01,synthetic-current,,JPY,2,,3\n";
  function publish(key: string, body: string, at: string, from: string | null) {
    const dataset = artifactDataset("sony-bank", {
      artifactKey: key,
      role: "provider_export",
      mediaType: "text/csv",
    });
    const run = store.run({
      source: "sony-bank",
      at,
      artifacts: [{ dataset: dataset ?? "unassigned", key }],
    });
    if (dataset === null) return;
    const meta: ArtifactMeta = {
      id: run.artifacts[0]!,
      sourceId: "sony-bank",
      runStatus: "success",
      runFailureCount: 0,
      dataset,
      mime: "text/csv",
      url: null,
      fetchedAt: at,
      sha256: "0".repeat(64),
      ...(from === null
        ? { retainedHistoryEnd: "2099-04-02" }
        : { runWindow: { from, to: "2099-04-02" } }),
    };
    expect(sonyBankHistoryCsv.accepts(meta)).toBe(true);
    const rows = sonyBankHistoryCsv
      .parse(new TextEncoder().encode(header + body), meta)
      .observations.filter((row): row is TransactionObservation => row.kind === "transaction");
    parsed(store, meta.id, sonyBankHistoryCsv.name, rows);
  }
  try {
    // The run on April 1 was missed; the older monthly data never saw March 31.
    publish("yen-history.csv", recent, "2099-04-02T00:00:00Z", "2099-04-01");
    expect(current(store)).toHaveLength(1);
    // New monthly capture is preserved as evidence without getting a dataset.
    expect(
      artifactDataset("sony-bank", {
        artifactKey: "monthly-yen-history.csv",
        role: "provider_export",
        mediaType: "text/csv",
      }),
    ).toBeNull();
    publish("monthly-yen-history.csv", recent, "2099-04-03T00:00:00Z", null);
    expect(current(store)).toHaveLength(1);
    // Retained CSV includes two truly identical rows. Preserve both occurrences.
    publish("yen-history.csv", old + recent + recent, "2099-04-03T00:00:00Z", null);
    const rows = current(store);
    expect(rows).toHaveLength(3);
    expect(rows.filter((row) => row.description === "synthetic-month-end")).toHaveLength(1);
    expect(rows.filter((row) => row.description === "synthetic-current")).toHaveLength(2);
    expect(new Set(rows.map((row) => row.external_id)).size).toBe(3);
    publish("yen-history.csv", recent + recent + old, "2099-04-04T00:00:00Z", null);
    expect(
      current(store)
        .map((row) => row.external_id)
        .sort(),
    ).toEqual(rows.map((row) => row.external_id).sort());
  } finally {
    store.db.close();
  }
});
